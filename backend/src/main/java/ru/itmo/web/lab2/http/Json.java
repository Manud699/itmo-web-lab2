package ru.itmo.web.lab2.http;

/** Small helper to write JSON by hand without external libraries. */
public class Json {

    public static final String CONTENT_TYPE = "application/json; charset=utf-8";

    /** Returns the text as a JSON string literal: wrapped in quotes and with special characters escaped. */
    public String quote(String text) {
        StringBuilder sb = new StringBuilder("\"");
        for (char c : text.toCharArray()) {
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
                }
            }
        }
        return sb.append('"').toString();
    }
}